package com.kitakkun.jetwhale.protocol.gradle

import org.gradle.api.DefaultTask
import org.gradle.api.GradleException
import org.gradle.api.file.ConfigurableFileCollection
import org.gradle.api.file.DirectoryProperty
import org.gradle.api.provider.Property
import org.gradle.api.tasks.CacheableTask
import org.gradle.api.tasks.Input
import org.gradle.api.tasks.InputFiles
import org.gradle.api.tasks.OutputDirectory
import org.gradle.api.tasks.PathSensitive
import org.gradle.api.tasks.PathSensitivity
import org.gradle.api.tasks.TaskAction

/**
 * Writes the module's `JetWhalePluginContract` as Kotlin source, and as
 * `META-INF/jetwhale/protocols/<pluginId>.json` for the JVM jar, where a build reads it without
 * loading a class.
 */
@CacheableTask
internal abstract class GenerateJetWhalePluginContractTask : DefaultTask() {
    @get:Input
    abstract val pluginId: Property<String>

    @get:Input
    abstract val releaseVersion: Property<String>

    @get:Input
    abstract val protocolRevision: Property<Int>

    @get:Input
    abstract val contractQualifiedName: Property<String>

    /** `wire/<project>.wire`, which does not exist before the first `dumpWireSchema`. */
    @get:InputFiles
    @get:PathSensitive(PathSensitivity.NONE)
    abstract val committedWireSchema: ConfigurableFileCollection

    @get:OutputDirectory
    abstract val kotlinSourceDirectory: DirectoryProperty

    @get:OutputDirectory
    abstract val resourceDirectory: DirectoryProperty

    @TaskAction
    fun generateContract() {
        val pluginId = pluginId.get()
        val releaseVersion = releaseVersion.get()
        val protocolRevision = protocolRevision.get()
        val contractQualifiedName = contractQualifiedName.get()
        if (pluginId.isBlank() || pluginId.any { it == '/' || it == '\\' }) {
            throw GradleException("jetwhaleProtocol.pluginId must be a plugin id such as com.example.myplugin, not '$pluginId'.")
        }
        if (protocolRevision < 1) {
            throw GradleException("jetwhaleProtocol.protocolRevision starts at 1, but it is $protocolRevision.")
        }
        if (!contractQualifiedName.matches(QUALIFIED_NAME)) {
            throw GradleException("jetwhaleProtocol.contractQualifiedName must be a qualified Kotlin name such as com.example.MyPluginContract, not '$contractQualifiedName'.")
        }
        if (releaseVersion == UNSPECIFIED_VERSION) {
            throw GradleException("Set the module's version: it is the plugin's release version, which the contract carries.")
        }
        val wireSchemaHash = committedWireSchema.files.singleOrNull { it.isFile }?.let { WireSchema.parse(it.readText()).hash() }

        val packageName = contractQualifiedName.substringBeforeLast('.', missingDelimiterValue = "")
        val propertyName = contractQualifiedName.substringAfterLast('.')
        val kotlinSourceDirectory = kotlinSourceDirectory.get().asFile
        kotlinSourceDirectory.deleteRecursively()
        kotlinSourceDirectory.resolve(packageName.replace('.', '/')).resolve("$propertyName.kt").apply {
            parentFile.mkdirs()
            writeText(
                buildString {
                    appendLine("// Generated by the com.kitakkun.jetwhale.protocol Gradle plugin from jetwhaleProtocol and the wire schema dump.")
                    if (packageName.isNotEmpty()) {
                        appendLine()
                        appendLine("package $packageName")
                    }
                    appendLine()
                    appendLine("import com.kitakkun.jetwhale.protocol.negotiation.JetWhalePluginContract")
                    appendLine()
                    appendLine("/** The wire contract of $pluginId: its release version, protocol revision and wire schema hash. */")
                    appendLine("public val $propertyName: JetWhalePluginContract = JetWhalePluginContract(")
                    appendLine("    pluginId = \"${kotlinStringContent(pluginId)}\",")
                    appendLine("    releaseVersion = \"${kotlinStringContent(releaseVersion)}\",")
                    appendLine("    protocolRevision = $protocolRevision,")
                    appendLine("    wireSchemaHash = ${wireSchemaHash?.let { "\"$it\"" } ?: "null"},")
                    appendLine(")")
                },
            )
        }

        val resourceDirectory = resourceDirectory.get().asFile
        resourceDirectory.deleteRecursively()
        resourceDirectory.resolve("META-INF/jetwhale/protocols/$pluginId.json").apply {
            parentFile.mkdirs()
            writeText(
                buildString {
                    appendLine("{")
                    appendLine("  \"pluginId\": \"${jsonStringContent(pluginId)}\",")
                    appendLine("  \"releaseVersion\": \"${jsonStringContent(releaseVersion)}\",")
                    appendLine("  \"protocolRevision\": $protocolRevision,")
                    appendLine("  \"wireSchemaHash\": ${wireSchemaHash?.let { "\"$it\"" } ?: "null"}")
                    appendLine("}")
                },
            )
        }
    }

    private fun kotlinStringContent(value: String): String = value
        .replace("\\", "\\\\")
        .replace("\"", "\\\"")
        .replace("$", "\\$")

    private fun jsonStringContent(value: String): String = buildString {
        value.forEach { char ->
            when {
                char == '"' -> append("\\\"")
                char == '\\' -> append("\\\\")
                char < ' ' -> append("\\u%04x".format(char.code))
                else -> append(char)
            }
        }
    }

    private companion object {
        const val UNSPECIFIED_VERSION = "unspecified"
        val QUALIFIED_NAME = Regex("([A-Za-z_][A-Za-z0-9_]*\\.)*[A-Za-z_][A-Za-z0-9_]*")
    }
}
